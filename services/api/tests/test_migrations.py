from app import models  # noqa: F401 -- registers tables on SQLModel.metadata
from app.config import get_settings

#: Alembic creates this to track applied revisions. It is not a model, so it
#: is expected in the database and absent from the metadata.
ALEMBIC_TABLE = "alembic_version"

API_DIR = pathlib.Path(__file__).resolve().parents[1]
ALEMBIC_EXE = API_DIR / ".venv" / "Scripts" / "alembic.exe"


def _scratch_name() -> str:
    return f"trace_migtest_{uuid.uuid4().hex[:10]}"


def _base_url() -> str:
    """Server URL with the database name stripped off."""
    return get_settings().DATABASE_URL.rsplit("/", 1)[0]


@pytest.fixture
async def migrated_db():
    """A database built purely by running the migrations, then thrown away."""
    name = _scratch_name()

    # THE GUARD. This fixture drops a database at the end. Anything other than
    # a freshly-generated scratch name means something has gone wrong, and the
    # cost of being wrong here is real data.
    assert name.startswith("trace_migtest_"), name
    assert name not in ("trace", "trace_test"), name

    base = _base_url()
    admin = create_async_engine(f"{base}/postgres", isolation_level="AUTOCOMMIT")
    async with admin.connect() as conn:
        await conn.execute(text(f'CREATE DATABASE "{name}"'))

    try:
        # Point ONLY this subprocess at the scratch database. pydantic-settings
        # reads the environment ahead of .env, which is the same mechanism
        # conftest.py uses to redirect the suite at trace_test.
        env = dict(os.environ, DATABASE_URL=f"{base}/{name}")
        result = subprocess.run(
            [str(ALEMBIC_EXE), "upgrade", "head"],
            cwd=str(API_DIR),
            env=env,
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, (
            "alembic upgrade head failed on a fresh database.\n\n"
            f"stdout:\n{result.stdout[-2000:]}\n\nstderr:\n{result.stderr[-3000:]}"
        )
        yield f"{base}/{name}"
    finally:
        async with admin.connect() as conn:
            # Terminate stragglers first; Postgres refuses to drop a database
            # that still has connections, and a failure here would leak a
            # scratch database on every run.
            await conn.execute(
                text(
                    "SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                    "WHERE datname = :n AND pid <> pg_backend_pid()"
                ),
                {"n": name},
            )
            await conn.execute(text(f'DROP DATABASE IF EXISTS "{name}"'))
        await admin.dispose()


async def _inspect(url: str) -> dict:
    engine = create_async_engine(url)
    try:
        async with engine.begin() as conn:
            tables = {
                r[0]
                for r in (
                    await conn.execute(
                        text(
                            "SELECT tablename FROM pg_tables "
                            "WHERE schemaname = 'public'"
                        )
                    )
                ).all()
            }
            cols: dict[str, set[str]] = {}
            for t, c in (
                await conn.execute(
                    text(
                        "SELECT table_name, column_name FROM "
                        "information_schema.columns WHERE table_schema = 'public'"
                    )
                )
            ).all():
                cols.setdefault(t, set()).add(c)
            indexes = {
                r[0]
                for r in (
                    await conn.execute(
                        text(
                            "SELECT indexname FROM pg_indexes "
                            "WHERE schemaname = 'public'"
                        )
                    )
                ).all()
            }
            extensions = {
                r[0]
                for r in (await conn.execute(text("SELECT extname FROM pg_extension"))).all()
            }
            trgm = (
                await conn.execute(
                    text(
                        "SELECT indexdef FROM pg_indexes "
                        "WHERE indexname = 'ix_food_search_trgm'"
                    )
                )
            ).scalar()
        return {
            "tables": tables,
            "cols": cols,
            "indexes": indexes,
            "extensions": extensions,
            "trgm": trgm or "",
        }
    finally:
        await engine.dispose()


class TestMigrationsBuildTheSchema:
    async def test_every_model_table_is_created(self, migrated_db):
        found = await _inspect(migrated_db)
        expected = set(SQLModel.metadata.tables)
        assert not (expected - found["tables"]), (
            "migrations did not create: " f"{sorted(expected - found['tables'])}"
        )

    async def test_no_unexpected_tables(self, migrated_db):
        found = await _inspect(migrated_db)
        extra = found["tables"] - set(SQLModel.metadata.tables) - {ALEMBIC_TABLE}
        assert not extra, f"migrations created tables no model declares: {sorted(extra)}"

    async def test_no_column_drift(self, migrated_db):
        """The check that catches a migration falling behind the models."""
        found = await _inspect(migrated_db)
        drift = {}
        for name, table in SQLModel.metadata.tables.items():
            missing = {c.name for c in table.columns} - found["cols"].get(name, set())
            if missing:
                drift[name] = sorted(missing)
        assert not drift, f"columns in the models but not in the migrations: {drift}"

    async def test_extensions_are_created_by_the_migration(self, migrated_db):
        """Autogenerate cannot see extensions -- they are added by hand.

        If someone regenerates the baseline and loses the CREATE EXTENSION
        lines, a fresh database silently loses trigram search. This is the only
        thing that would notice.
        """
        found = await _inspect(migrated_db)
        assert "pg_trgm" in found["extensions"]
        assert "unaccent" in found["extensions"]

    async def test_the_search_index_keeps_its_operator_class(self, migrated_db):
        """THE ONE THAT PROTECTS FOOD SEARCH.

        `ix_food_search_trgm` is only useful with `gin_trgm_ops`. Rebuilt
        without it, the index still exists, the app still starts, every other
        test still passes -- and food search silently returns to the
        sequential scan that took 10 seconds a query.
        """
        found = await _inspect(migrated_db)
        assert "ix_food_search_trgm" in found["indexes"]
        assert "gin_trgm_ops" in found["trgm"], (
            "the trigram index was rebuilt without gin_trgm_ops -- "
            f"food search will fall back to a sequential scan:\n{found['trgm']}"
        )
        assert "USING gin" in found["trgm"]

    async def test_the_phone_index_exists(self, migrated_db):
        """Drift found during the Alembic adoption audit, fixed by revision 2."""
        found = await _inspect(migrated_db)
        assert "ix_users_phone" in found["indexes"]


