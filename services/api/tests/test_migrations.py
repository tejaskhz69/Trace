"""Do the migrations actually build the schema the models describe?

WHY THIS EXISTS
`create_all` builds the schema for the rest of the test suite, which is fast
and keeps the suite worth running -- but it means nothing else in this project
ever executes a migration. Without this file, `alembic/versions/` could drift
arbitrarily far from `app/models.py` and every one of the other 690 tests
would still pass, right up until someone tried to build a fresh database and
found the migrations broken.

So this is the one test that runs them for real. It builds a throwaway
database from `alembic upgrade head` and compares the result against
`SQLModel.metadata`.

IT NEVER TOUCHES `trace` OR `trace_test`. A uniquely-named scratch database is
created, used, and dropped -- and the name is asserted before anything runs,
because a bug here would be a bug that deletes real data.

WHAT IT WOULD HAVE CAUGHT, had it existed earlier: the baseline migration was
generated using `sqlmodel.sql.sqltypes.AutoString()` 101 times without an
`import sqlmodel`. Stamping never runs the body, so the omission was invisible
-- the first person to build a database from scratch would have hit
`NameError`. Every future autogenerated revision has the same gap.
"""

from __future__ import annotations

import json
import os
import pathlib
import subprocess
import uuid
from contextlib import asynccontextmanager

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine
